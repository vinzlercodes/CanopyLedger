"""Generate or check the deterministic TypeScript API client."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
OPENAPI_PATH = ROOT / "docs/api/openapi-v1.json"
GENERATED_PATH = ROOT / "typescript/generated/index.ts"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="overwrite generated client")
    args = parser.parse_args()
    expected = generate_client(json.loads(OPENAPI_PATH.read_text()))
    if args.write:
        GENERATED_PATH.parent.mkdir(parents=True, exist_ok=True)
        GENERATED_PATH.write_text(expected)
        return 0
    if not GENERATED_PATH.exists():
        print(f"missing generated client: {GENERATED_PATH.relative_to(ROOT)}")
        return 1
    actual = GENERATED_PATH.read_text()
    if actual != expected:
        print(f"generated client drift: {GENERATED_PATH.relative_to(ROOT)}")
        return 1
    return 0


def generate_client(document: dict[str, Any]) -> str:
    schemas = document["components"]["schemas"]
    lines = [
        "/* eslint-disable */",
        "// Generated by scripts/check_typescript_client.py. Do not edit manually.",
        "",
    ]
    for name in sorted(schemas):
        lines.extend(_interface(name, schemas[name]))
        lines.append("")
    lines.extend(
        [
            "export type RequestHeaders = Record<string, string>;",
            "",
            "export interface ClientOptions {",
            "  readonly baseUrl: string;",
            "  readonly fetchImpl?: typeof fetch;",
            "  readonly defaultHeaders?: RequestHeaders;",
            "}",
            "",
            "export interface ApiResponse<T> {",
            "  readonly status: number;",
            "  readonly headers: Headers;",
            "  readonly data: T;",
            "}",
            "",
            "export class CanopyLedgerClient {",
            "  readonly #baseUrl: string;",
            "  readonly #fetchImpl: typeof fetch;",
            "  readonly #defaultHeaders: RequestHeaders;",
            "",
            "  constructor(options: ClientOptions) {",
            '    this.#baseUrl = options.baseUrl.replace(/\\/$/, "");',
            "    this.#fetchImpl = options.fetchImpl ?? fetch;",
            "    this.#defaultHeaders = options.defaultHeaders ?? {};",
            "  }",
            "",
        ]
    )
    operations = _operations(document["paths"])
    for operation in operations:
        lines.extend(_method(operation))
        lines.append("")
    if any(operation["query_parameters"] for operation in operations):
        lines.extend(_private_query_method())
        lines.append("")
    lines.extend(_private_request_method())
    lines.extend(["}", ""])
    return "\n".join(lines)


def _interface(name: str, schema: dict[str, Any]) -> list[str]:
    required = set(schema.get("required", []))
    lines = [f"export interface {name} {{"]
    for property_name, property_schema in sorted(schema.get("properties", {}).items()):
        optional = "" if property_name in required else "?"
        lines.append(f"  readonly {property_name}{optional}: {_ts_type(property_schema)};")
    lines.append("}")
    return lines


def _ts_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_ts_type(item) for item in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    schema_type = schema.get("type")
    if schema_type == "array":
        prefix_items = schema.get("prefixItems")
        if isinstance(prefix_items, list):
            return "readonly [" + ", ".join(_ts_type(item) for item in prefix_items) + "]"
        item_type = _ts_type(schema["items"])
        if " | " in item_type or item_type.startswith("readonly "):
            item_type = f"({item_type})"
        return f"readonly {item_type}[]"
    if schema_type == "integer" or schema_type == "number":
        return "number"
    if schema_type == "boolean":
        return "boolean"
    if schema_type == "null":
        return "null"
    if schema_type == "object":
        additional_properties = schema.get("additionalProperties")
        if isinstance(additional_properties, dict):
            return f"Record<string, {_ts_type(additional_properties)}>"
        return "Record<string, unknown>"
    return "string"


def _operations(paths: dict[str, Any]) -> list[dict[str, Any]]:
    operations = []
    for path, methods in paths.items():
        for method, operation in methods.items():
            success = sorted(code for code in operation["responses"] if code.startswith("2"))[0]
            response_schema = operation["responses"][success]["content"]["application/json"][
                "schema"
            ]
            request_schema = (
                operation.get("requestBody", {})
                .get("content", {})
                .get("application/json", {})
                .get("schema")
            )
            operations.append(
                {
                    "operation_id": operation["operationId"],
                    "method": method.upper(),
                    "path": path,
                    "request_type": _ts_type(request_schema) if request_schema else None,
                    "response_type": _ts_type(response_schema),
                    "query_parameters": [
                        {
                            "name": parameter["name"],
                            "type": _ts_type(parameter["schema"]),
                            "required": parameter.get("required", False),
                        }
                        for parameter in operation.get("parameters", [])
                        if parameter.get("in") == "query"
                    ],
                }
            )
    return sorted(operations, key=lambda item: item["operation_id"])


def _method(operation: dict[str, Any]) -> list[str]:
    name = operation["operation_id"]
    path_params = [part[1:-1] for part in operation["path"].split("/") if part.startswith("{")]
    params = [f"{param}: string" for param in path_params]
    if operation["request_type"] is not None:
        params.append(f"body: {operation['request_type']}")
    if operation["query_parameters"]:
        params.append(f"query: {_query_type(operation['query_parameters'])} = {{}}")
    params.append("headers: RequestHeaders = {}")
    signature = (
        f"  async {name}({', '.join(params)}): "
        f"Promise<ApiResponse<{operation['response_type']}>> {{"
    )
    path = f"`{_template_path(operation['path'])}`"
    if operation["query_parameters"]:
        path = f"this.#withQuery({path}, query)"
    lines = [
        signature,
        f"    return this.#request<{operation['response_type']}>(",
        f'      "{operation["method"]}",',
        f"      {path},",
    ]
    if operation["request_type"] is None:
        lines.append("      undefined,")
    else:
        lines.append("      body,")
    lines.extend(
        [
            "      headers,",
            "    );",
            "  }",
        ]
    )
    return lines


def _query_type(parameters: list[dict[str, Any]]) -> str:
    fields = []
    for parameter in parameters:
        optional = "" if parameter["required"] else "?"
        fields.append(f"readonly {parameter['name']}{optional}: {parameter['type']}")
    return "{ " + "; ".join(fields) + " }"


def _template_path(path: str) -> str:
    return path.replace("{", "${encodeURIComponent(").replace("}", ")}")


def _private_query_method() -> list[str]:
    return [
        "  #withQuery(",
        "    path: string,",
        "    query: object,",
        "  ): string {",
        "    const parameters = new URLSearchParams();",
        "    for (const [name, value] of Object.entries(query)) {",
        "      if (value !== undefined) parameters.set(name, String(value));",
        "    }",
        "    const serialized = parameters.toString();",
        '    return serialized ? path + "?" + serialized : path;',
        "  }",
    ]


def _private_request_method() -> list[str]:
    return [
        "",
        "  async #request<T>(",
        "    method: string,",
        "    path: string,",
        "    body: unknown,",
        "    headers: RequestHeaders,",
        "  ): Promise<ApiResponse<T>> {",
        "    const init: RequestInit = {",
        "      method,",
        "      cache: \"no-store\",",
        "      headers: {",
        "        ...this.#defaultHeaders,",
        "        ...headers,",
        '        ...(body === undefined ? {} : { "Content-Type": "application/json" }),',
        "      },",
        "    };",
        "    if (body !== undefined) {",
        "      init.body = JSON.stringify(body);",
        "    }",
        "    const response = await this.#fetchImpl(`${this.#baseUrl}${path}`, init);",
        "    const data = (await response.json()) as T;",
        "    return { status: response.status, headers: response.headers, data };",
        "  }",
    ]


if __name__ == "__main__":
    raise SystemExit(main())
